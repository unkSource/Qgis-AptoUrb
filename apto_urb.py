    def add_lc_project(self, lc_file_path):
        selected_layer_name = self.dlg.comboBoxSHP.currentText()
        year_image = self.dlg.dateEditYear.date().year()

        raster_layer = QgsRasterLayer(lc_file_path, f"Uso e Cobertura do Solo - {selected_layer_name} {year_image}")

        if raster_layer.isValid():
            classes_list = {
                1: ("#1A5BAB", "Água"),
                2: ("#358221", "Vegetação Densa"), 
                4: ("#87D19E", "Vegetação inundada"),
                5: ("#4D453E", "Agricultura/Culturas"), 
                7: ("#ED022A", "Área Construída"), 
                8: ("#FDE9D5", "Solo Exposto"),
                9: ("#C2D3EF", "Gelo/Neve"), 
                10: ("#DBDBDB", "Nuvens"), 
                11: ("#61A5DE", "Pastagem")}
        
        #Identificar as classes
        provider = raster_layer.dataProvider()

        extent = raster_layer.extent()
        block = provider.block(
            1, extent, raster_layer.width(), raster_layer.height())

        pixel_values = np.unique(block.data()).tolist()

        classes = []
        for value, (color, classe) in classes_list.items():
            # Verifica se o valor da classe mestre faz parte do intervalo do raster descarregado
            if value in pixel_values:
                classes.append(QgsPalettedRasterRenderer.Class(
                    value, QColor(color), classe))
        
        # 2. Cria as classes e aplica o renderizador em apenas 2 linhas
        if classes:
            renderer = QgsPalettedRasterRenderer(provider, 1, classes)
            raster_layer.setRenderer(renderer)
            raster_layer.triggerRepaint()

        # 3. Finaliza adicionando ao projeto e atualizando a UI
        QgsProject.instance().addMapLayer(raster_layer)
        self.dlg.comboBoxLC.setLayer(raster_layer)
        self.set_table_land_cover()
    
    def set_table_land_cover(self):
        self.dlg.tableWidgetLC.setRowCount(0)

        # 1. Validações iniciais unificadas
        layer_name = self.dlg.comboBoxLC.currentText()
        layers = QgsProject.instance().mapLayersByName(layer_name) if layer_name else []
        if not layers:
            return

        raster_layer = layers[0]
        if raster_layer.type() != QgsRasterLayer.RasterLayer:
            return self.dlg.textBrowser.append("\nA camada selecionada não é um arquivo Raster.")

        # 2. Identifica o renderizador e extrai as classes
        renderer = raster_layer.renderer()
        is_paletted = isinstance(renderer, QgsPalettedRasterRenderer)
        classes_raster = renderer.classes() if is_paletted else (renderer.usesBands()
                                                                if isinstance(renderer, QgsSingleBandColorDataRenderer) else [])

        if not classes_raster:
            return self.message.error(
                "3. Arquivo de entrada Raster Uso e Cobertura de Terra:\n"
                "O raster selecionado não possui uma tabela de classes discretas (1., 2., 3., ...).\n\n"
                "Para corrigir, faça a classificação do seu raster nas Propriedades do raster:\n"
                "Simbologia>Paletizado/valores unicos."
            )

        self.dlg.tableWidgetLC.setRowCount(len(classes_raster))

        # 3. Função auxiliar interna para cortar linhas repetitivas de criação de itens
        def create_item(text, editable=False, color=None):
            item = QTableWidgetItem(text)
            item.setFlags(item.flags() | Qt.ItemIsEditable if editable else item.flags() & ~Qt.ItemIsEditable)
            if color:
                item.setBackground(QBrush(color))
            return item

        # 4. Preenche a tabela
        for row, classe in enumerate(classes_raster):
            # Operador ternário limpa todo o bloco if/else anterior
            v = classe.value if is_paletted else row
            color = classe.color if is_paletted else QColor(130, 130, 130)
            lbl = (classe.label.strip() if classe.label.strip()
                else f"Classe {v}") if is_paletted else f"Classe {v}"

            # Aloca os itens usando a função auxiliar
            self.dlg.tableWidgetLC.setItem(row, 0, create_item(str(int(v))))
            self.dlg.tableWidgetLC.setItem(row, 1, create_item("", color=color))
            self.dlg.tableWidgetLC.setItem(row, 2, create_item(lbl, editable=True))

            # Embutir o QSpinBox diretamente
            spin = QSpinBox(minimum=1, maximum=5, value=1, alignment=Qt.AlignCenter)
            self.dlg.tableWidgetLC.setCellWidget(row, 3, spin)

    # Recuperar informações da tabela
