    def get_crs_utm(self, layer):
        # Pega a longitude centro da tua área de estudo
        bbox = layer.extent()
        center_geom = bbox.center()

        crs_wgs84 = QgsCoordinateReferenceSystem("EPSG:4326")
        transform = QgsCoordinateTransform(layer.crs(), crs_wgs84, QgsProject.instance())
        center_graus = transform.transform(center_geom)

        center_x = center_graus.x()

        # Em Moçambique, a linha divisória aproximada entre o fuso 36 e 37 é o meridiano 39°E
        # Para a província de Tete, a transição ocorre por volta do meridiano 36°E
        if center_x <= 36.0:
            epsg_correct = "EPSG:2736"  # UTM 36S
        else:
            epsg_correct = "EPSG:2737"  # UTM 37S

        return epsg_correct

