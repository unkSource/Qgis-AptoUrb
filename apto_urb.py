    def add_final_raster_qgis(self,state, layer_path):
        layer = QgsRasterLayer(
            layer_path, "Adequabilidade a Expansão Urbana")

        if not layer.isValid():
            self.bar.pushMessage(
                "Aviso", 
                "Erro ao carregar o raster gerado!",
                level=Qgis.Critical, duration=5
            )
            return
        
        #QgsProject.instance().addMapLayer(layer)

        # 1. Mapeamento direto: {Valor: (Cor_RGB, "Nome da Classe")}
        if layer.isValid():
            classes_list = {
                1: ("#FFF4DF", "1. Adequado (0 - 0,25)"),
                2: ("#F1CB79", "2. Media Aptidão (0,25 - 0,50)"),
                3: ("#F38B4F", "3. Baixa Aptidão (0,50 - 0,75)"),
                4: ("#BE4040", "4. Inadequado (> 0,75)")}

        provider = layer.dataProvider()
        extent = layer.extent()
        block = provider.block(
            1, extent, layer.width(), layer.height())
        
        pixel_values = np.unique(block.data()).tolist()
        classes = []

        for value, (color, classe) in classes_list.items():
                if value in pixel_values:
                    classes.append(QgsPalettedRasterRenderer.Class(
                        value, QColor(color), classe))
        # 2. Gera a paleta nativa automaticamente a partir da banda 1
        if classes:
                renderer = QgsPalettedRasterRenderer(provider, 1, classes)
                layer.setRenderer(renderer)
                layer.triggerRepaint()

        QgsProject.instance().addMapLayer(layer)


    def calc_shapefile_area(self, layer: QgsVectorLayer) -> float:
        if not layer or not layer.isValid():
            return 0.0

        total_area = 0.0

        # 3. Itera e soma as áreas
        for feature in layer.getFeatures():
            if feature.hasGeometry():
                total_area += feature.geometry().area()

        return total_area


    def execute_processing(self, mde_input, temp_folder_path):
        selected_shapefile_layer = self.dlg.comboBoxSHP.currentLayer()
        study_area = self.calc_shapefile_area(selected_shapefile_layer)
        crs_utm = self.get_crs_utm(selected_shapefile_layer)

        if isinstance(mde_input, QgsRasterLayer):
            mde = mde_input.source()
        else:
            mde = str(mde_input)

        raster_lc_input = self.dlg.comboBoxLC.currentLayer()

        lc_data = self.get_table_data()

        final_raster_path = self.dlg.lineEditSave.text().strip()

        if not final_raster_path:
            final_raster_path = os.path.join(
                temp_folder_path, "aptidao_urbana_final.tif")
        
        self.processig_task = PipelineTask(
            layer_mask_area=study_area,
            layer_mask=selected_shapefile_layer,
            mde_input=mde,
            lc_input=raster_lc_input,
            lc_data_table=lc_data,
            crs_utm=crs_utm,
            temp_folder=temp_folder_path,
            final_raster=final_raster_path
        )

        # 3. Conecta os sinais da Task aos elementos da tua UI dialog (dlg)
        self.processig_task.log_text_browser.connect(self.dlg.textBrowser.append)
        self.processig_task.progressChanged.connect(lambda progress:
                                                   self.dlg.progressBar.setValue(int(progress)))
        self.processig_task.completed.connect(self.on_process_finished)
        self.processig_task.completed.connect(self.add_final_raster_qgis)

        self.dlg.pushButtonCancel.setEnabled(True)

        # 4. Envia para o QGIS executar em Background
        QgsApplication.taskManager().addTask(self.processig_task)
    

    
